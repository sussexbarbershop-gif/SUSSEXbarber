/**
 * The database, and the shape the site expects to read it in.
 *
 * Neon's driver talks SQL over HTTPS rather than holding a socket open, which
 * is what makes it usable from a function that may only live for 200ms. No
 * pool to warm, nothing to close.
 *
 * Times come back as 'HH:MM:SS' and dates as 'YYYY-MM-DD' — both already the
 * strings the front end wants, which is the whole reason for typed columns.
 * Sheets handed back a Date for a cell reading "10:00" and a string for the
 * same cell in the next row; formatClock() existed to paper over that.
 */

const { neon } = require('@neondatabase/serverless');

let cachedSql = null;

/** The query function. Tagged template — parameters are never interpolated. */
function db() {
  if (cachedSql) return cachedSql;
  const url = process.env.DATABASE_URL;
  if (!url) {
    throw new Error('DATABASE_URL is not set. Add it in Vercel > Settings > Environment Variables.');
  }
  cachedSql = neon(url);
  return cachedSql;
}

/**
 * The parts of the schema that arrived after the database was already in use,
 * added on demand.
 *
 * `CREATE TABLE IF NOT EXISTS` does nothing whatsoever to a table that already
 * exists, so re-running db/schema.sql does not add a column to a live
 * database. The statements to do that are at the foot of that file — but "the
 * shop must remember to run some SQL before the next deploy or bookings stop"
 * is not a deployment step, it is a trap.
 *
 * So the code repairs the shape itself, and only when it finds it wrong: the
 * normal path runs no extra query at all. `withNewSchema` catches the two
 * errors Postgres raises for a column or a table that is not there, runs the
 * statements, and tries again. Every one of them is IF NOT EXISTS, so a second
 * process racing this does no harm.
 */
let schemaEnsured = null;

function ensureSchema() {
  if (!schemaEnsured) {
    const sql = db();
    schemaEnsured = (async () => {
      await sql`ALTER TABLE bookings ADD COLUMN IF NOT EXISTS source text NOT NULL DEFAULT 'web'`;
      await sql`ALTER TABLE bookings ADD COLUMN IF NOT EXISTS lang text NOT NULL DEFAULT 'en'`;
      await sql`ALTER TABLE bookings ADD COLUMN IF NOT EXISTS reminded_at timestamptz`;
      await sql`ALTER TABLE bookings ADD COLUMN IF NOT EXISTS review_asked_at timestamptz`;
      await sql`CREATE TABLE IF NOT EXISTS rate_limit (
                  bucket    text NOT NULL,
                  window_at timestamptz NOT NULL,
                  hits      integer NOT NULL DEFAULT 0,
                  PRIMARY KEY (bucket, window_at))`;
      await sql`CREATE INDEX IF NOT EXISTS rate_limit_sweep ON rate_limit (window_at)`;

      // One row per person, keyed on the last nine digits of their number.
      // See db/schema.sql for what it is for; the short version is that a
      // discount or a loyalty count is a fact about a customer, and the diary
      // can only answer questions about bookings.
      await sql`CREATE TABLE IF NOT EXISTS customers (
                  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  phone_key  text NOT NULL UNIQUE,
                  name       text NOT NULL DEFAULT '',
                  email      text NOT NULL DEFAULT '',
                  note       text NOT NULL DEFAULT '',
                  first_seen timestamptz NOT NULL DEFAULT now(),
                  last_seen  timestamptz NOT NULL DEFAULT now())`;
      await sql`ALTER TABLE bookings ADD COLUMN IF NOT EXISTS customer_id integer`;
      await sql`CREATE INDEX IF NOT EXISTS bookings_by_customer ON bookings (customer_id)`;

      // The diary already holds every customer the shop has; this is the one
      // pass that turns those numbers into rows. Re-running it does nothing:
      // the insert skips numbers that are already there and the update only
      // touches bookings that have no customer yet.
      await sql`
        INSERT INTO customers (phone_key, name, email, first_seen, last_seen)
        SELECT phone_key,
               (array_agg(customer_name ORDER BY created_at DESC))[1],
               COALESCE((array_agg(NULLIF(email, '') ORDER BY created_at DESC))[1], ''),
               min(created_at), max(created_at)
          FROM bookings
         WHERE phone_key <> ''
         GROUP BY phone_key
        ON CONFLICT (phone_key) DO NOTHING`;
      await sql`
        UPDATE bookings b SET customer_id = c.id
          FROM customers c
         WHERE b.customer_id IS NULL AND b.phone_key = c.phone_key`;
    })();
    // A failure must not be remembered as a success. Clearing it means the
    // next request tries again rather than every request after a blip
    // resolving instantly against a rejected promise.
    schemaEnsured.catch(() => { schemaEnsured = null; });
  }
  return schemaEnsured;
}

/**
 * 42703 is undefined_column, 42P01 undefined_table. The text is checked too:
 * some drivers hand back the message without the code.
 */
const isMissingSchema = err =>
  ['42703', '42P01'].includes(String((err && err.code) || '')) ||
  /(column|relation) .* does not exist/i.test(String((err && err.message) || ''));

/** Run a query; if it fails only because the schema is behind, catch up and retry once. */
async function withNewSchema(run) {
  try {
    return await run();
  } catch (err) {
    if (!isMissingSchema(err)) throw err;
    console.warn('[db] bringing the schema up to date; this database was behind');
    await ensureSchema();
    return await run();
  }
}

/** 'HH:MM:SS' or 'HH:MM' -> 'HH:MM'. Postgres returns seconds; nobody wants them. */
function hhmm(value) {
  if (!value) return '';
  return String(value).slice(0, 5);
}

const WEEKDAY_NAMES = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday',
                       'Friday', 'Saturday'];
const WEEKDAY_NL = ['Zondag', 'Maandag', 'Dinsdag', 'Woensdag', 'Donderdag',
                    'Vrijdag', 'Zaterdag'];

/** ISO weekday (1 = Monday) -> the index the site's arrays use (0 = Sunday). */
const isoToIndex = iso => (Number(iso) === 7 ? 0 : Number(iso));
const indexToIso = idx => (Number(idx) === 0 ? 7 : Number(idx));

/**
 * Everything the site needs to render itself, in one round trip.
 *
 * Seven queries, run together. Against Sheets this was seven sheet reads that
 * took twenty seconds between them, which is why there was a two-minute cache
 * in front of it and why the owner had to wait for their own edits to appear.
 * There is no cache here: the queries are indexed and the whole thing is a few
 * milliseconds, so what the owner saves is what the next visitor sees.
 */
async function readConfig() {
  const sql = db();

  const [settingsRows, barberRows, galleryRows, serviceRows, hourRows,
         barberHourRows, timeOffRows] = await Promise.all([
    sql`SELECT key, value FROM settings`,
    sql`SELECT id, name, image_url FROM barbers ORDER BY position, id`,
    sql`SELECT image_url FROM gallery ORDER BY position, id`,
    sql`SELECT id, name_en, name_nl, price, duration_min FROM services ORDER BY position, id`,
    sql`SELECT weekday, is_open, opens_at, closes_at FROM shop_hours`,
    sql`SELECT b.name, h.weekday, h.working, h.starts_at, h.ends_at,
               h.break_start, h.break_end
          FROM barber_hours h JOIN barbers b ON b.id = h.barber_id`,
    // to_char, not the raw date column. The driver hands a `date` back as a
    // JavaScript Date, and String()ing that gives
    // "Fri Aug 07 2026 00:00:00 GMT+0000 (Coordinated Universal Time)" —
    // which the site compares against 'YYYY-MM-DD' strings and never matches.
    sql`SELECT b.name, to_char(t.starts_on, 'YYYY-MM-DD') AS starts_on,
               to_char(t.ends_on, 'YYYY-MM-DD') AS ends_on, t.note
          FROM time_off t JOIN barbers b ON b.id = t.barber_id`
  ]);

  const settings = {};
  settingsRows.forEach(r => { settings[r.key] = r.value; });

  // The shop is described a day at a time, and a missing row means closed
  // rather than an absent day — the front end looks days up by name.
  const hoursByIndex = {};
  hourRows.forEach(r => { hoursByIndex[isoToIndex(r.weekday)] = r; });
  const hours = WEEKDAY_NAMES.map((day, i) => {
    const row = hoursByIndex[i];
    return {
      day,
      dayNL: WEEKDAY_NL[i],
      open: row ? row.is_open === true : false,
      from: row ? hhmm(row.opens_at) : '',
      to: row ? hhmm(row.closes_at) : ''
    };
  });

  const barberHours = {};
  barberHourRows.forEach(r => {
    if (!barberHours[r.name]) barberHours[r.name] = [];
    barberHours[r.name].push({
      day: WEEKDAY_NAMES[isoToIndex(r.weekday)],
      working: r.working === true,
      from: hhmm(r.starts_at),
      to: hhmm(r.ends_at),
      breakFrom: hhmm(r.break_start),
      breakTo: hhmm(r.break_end)
    });
  });

  return {
    settings,
    barbers: barberRows.map(r => ({ name: r.name, image: r.image_url || '' })),
    gallery: galleryRows.map(r => r.image_url),
    services: serviceRows.map(r => ({
      id: r.id,
      nameEN: r.name_en,
      nameNL: r.name_nl || r.name_en,
      price: Number(r.price),
      duration: r.duration_min
    })),
    hours,
    barberHours,
    timeOff: timeOffRows.map(r => ({
      barber: r.name,
      from: r.starts_on,
      to: r.ends_on,
      note: r.note || ''
    }))
  };
}

/**
 * The same config, plus the plain list of names the rota logic works from.
 * Kept separate from readConfig() because the site does not need it — it reads
 * `barbers` for the cards — and the rota does not want the images.
 */
async function readRotaConfig() {
  const config = await readConfig();
  config.barberNames = config.barbers.map(b => b.name);
  // Who gets a booking that named nobody, in the shop's own order. A setting
  // rather than a column: it is a preference the owner changes now and then,
  // not a fact about a barber, and it must not disturb the order the cards
  // appear in on the booking form.
  config.barberPriority = String(config.settings.barber_priority || '')
    .split(',').map(n => n.trim()).filter(Boolean);
  return config;
}

/**
 * The customer a phone number belongs to, creating the row on first sight.
 *
 * Called on every booking. The name and email are refreshed each time, so a
 * customer who books again under a corrected spelling is not two people with
 * two half-histories — the diary still keeps exactly what was typed for each
 * appointment, which is the record that has to stay honest.
 *
 * ON CONFLICT rather than a SELECT and then an INSERT: two bookings from the
 * same new number arriving together would both find nothing and both insert,
 * and the second would fail on the unique index. This is one statement and the
 * database settles it.
 *
 * Returns the id, or null when there is no usable number — the caller stores
 * that as-is, because a booking without a customer is still a booking.
 */
async function customerFor({ phone, name, email }) {
  const digits = String(phone || '').replace(/\D/g, '');
  const key = digits.length > 9 ? digits.slice(-9) : digits;
  if (!key) return null;

  const sql = db();
  const rows = await sql`
    INSERT INTO customers (phone_key, name, email)
    VALUES (${key}, ${String(name || '').trim()}, ${String(email || '').trim()})
    ON CONFLICT (phone_key) DO UPDATE
      SET name      = COALESCE(NULLIF(EXCLUDED.name, ''), customers.name),
          email     = COALESCE(NULLIF(EXCLUDED.email, ''), customers.email),
          last_seen = now()
    RETURNING id`;
  return rows.length ? rows[0].id : null;
}

module.exports = { db, customerFor, readConfig, readRotaConfig, hhmm, isoToIndex, indexToIso,
                   WEEKDAY_NAMES, WEEKDAY_NL,
                   ensureSchema, withNewSchema, isMissingSchema };
